int redone_verify_release_signature(const char *key_id,
                                    const uint8_t signature[64],
                                    const uint8_t *canonical_payload,
                                    size_t canonical_payload_length) {
    if (!key_id || !signature || !canonical_payload || !canonical_payload_length || canonical_payload_length > 8192)
        return -1;
    const uint8_t *key = NULL;
    if (strcmp(key_id, "redone-v1") == 0) key = redone_v1;
    else if (strcmp(key_id, "redone-v2") == 0) key = redone_v2;
    if (!key) return -1;
    return crypto_ed25519_check(signature, key, canonical_payload, canonical_payload_length);
}
